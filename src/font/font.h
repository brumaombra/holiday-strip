constexpr int GLYPH_ADVANCE = 6;

inline const Glyph *findGlyph(char c) {
	c = toupper(c);
	for (const auto &g : FONT) {
		if (g.c == c) {
			return &g;
		}
	}
	return nullptr;
}

inline int textWidth(const String &text) { return text.length() * GLYPH_ADVANCE; }

// Draws one character with its top-left corner at (x, y); color is chosen per column
template <typename ColorFn>
inline void drawChar(Frame &f, char c, int x, int y, ColorFn colorAt) {
	const Glyph *g = findGlyph(c);
	if (!g) {
		g = findGlyph('?');
	}
	for (int col = 0; col < 5; col++) {
		int px = x + col;
		if (px < 0 || px >= WIDTH) {
			continue;
		}
		for (int row = 0; row < 7; row++) {
			if (g->cols[col] & (1 << row)) {
				setPixel(f, px, y + row, colorAt(px, y + row));
			}
		}
	}
}